def _get_parameters(
    api_client: ConnectionApiClient, project_id: StrictStr, connection_id: int, include_hidden: bool = False
) -> List[IdeaParameter]:
    """
    Lists the connection's editable design parameters (e.g. plate
    thickness, bolt diameter, weld size) — these are what get_operations()
    itself does NOT expose; each ConOperation is just an id/name/type,
    while the actual dimensions live here, keyed by parameter `key`
    (whatever name the template author gave it in the desktop app).

    PREREQUISITE (per IDEA StatiCa's own docs): a GUI field like the
    "Thickness" box on a connecting plate is NOT automatically a
    parameter just because it's editable in the UI. The template author
    must open Developer Mode in the desktop app and explicitly link that
    field (a "Model property") to a named Parameter first. Only fields
    linked this way show up here / can be set via _set_parameters(); a
    field the template author didn't expose has no API-visible key at
    all, editable only by hand in the desktop app.
    """
    return api_client.parameter.get_parameters(project_id, connection_id, include_hidden)


def _find_parameters(
    api_client: ConnectionApiClient, project_id: StrictStr, connection_id: int, name_contains: str, include_hidden: bool = True
) -> List[IdeaParameter]:
    """
    Convenience filter over _get_parameters(): matches `name_contains`
    case-insensitively against each parameter's key OR description —
    useful for finding the parameter(s) belonging to one operation (e.g.
    "CPL3") without having to eyeball the full unfiltered list.
    """
    needle = name_contains.lower()
    return [
        p for p in _get_parameters(api_client, project_id, connection_id, include_hidden)
        if needle in (p.key or "").lower() or needle in (p.description or "").lower()
    ]


def _quote_expression_if_needed(expression: str) -> str:
    """
    IDEA StatiCa's expression parser treats a bare non-numeric token
    (e.g. bolt.type's "16 8.8") as a formula/identifier and fails to
    parse it — silently leaving the old `value` in place while still
    echoing the bad string back as `expression`. String-valued
    parameters must be quoted (e.g. '"16 8.8"'); numeric expressions
    must NOT be quoted, so only wrap it if it isn't already quoted and
    doesn't parse as a plain number.
    """
    expression = expression.strip()
    if not expression:
        return expression
    if (expression[0] == expression[-1] == '"') or (expression[0] == expression[-1] == "'"):
        return expression
    try:
        float(expression)
        return expression
    except ValueError:
        return f'"{expression}"'


def _set_parameters(
    api_client: ConnectionApiClient, project_id: StrictStr, connection_id: int, updates: List[Dict[str, str]]
) -> "ParameterUpdateResponse":
    """
    Sets one or more design parameters by key, each to a new expression
    (e.g. a plain number as a string, or a formula per IDEA StatiCa's
    parameter expression syntax). Raises if the service reports any
    failed validations (e.g. a value outside lower_bound/upper_bound).
    """
    param_updates = [
        IdeaParameterUpdate(key=u["key"], expression=_quote_expression_if_needed(str(u["expression"])))
        for u in updates
    ]
    response = api_client.parameter.update(project_id, connection_id, param_updates)
    print(f"parameter.update response: {to_json_convention_string(response)}")  # TODO: remove after debugging
    if response.failed_validations:
        raise IdeaStaticaJointError(f"Parameter update failed validation: {response.failed_validations}")
    return response


