def _run_design(design_spec_path: str) -> None:
    with open(design_spec_path) as f:
        data = json.load(f)
    result = design_joint(data)
    print(json.dumps(result, indent=2))


def _self_test(template_path: str) -> None:
    print("=== idea_statica_integration.py self-test (read-only) ===\n")

    print(f"1. Attaching to the Connection API service at {BASE_URL} ...")
    try:
        client_cm = _get_client()
    except Exception as exc:
        print(f"   FAIL: {exc}\n")
        return

    with client_cm as api_client:
        print("   PASS: attached.\n")

        print(f"2. Opening template project: {template_path} ...")
        try:
            api_client.project.open_project_from_filepath(template_path)
            project_id = api_client.project.active_project_id
            print(f"   PASS: opened, project_id={project_id}\n")
            settings = api_client.settings.get_settings(project_id)
            print(f"   Retrieved project settings: {to_json_convention_string(settings)}\n")
        except Exception as exc:
            print(f"   FAIL: {exc}\n")
            return

        print("3. Listing connections and members ...")
        try:
            connections = api_client.connection.get_connections(project_id)
            if not connections:
                print("   No connections found in this project.\n")
            for con in connections:
                repr_con = to_json_convention_string(con)
                print(f"   Connection id={con.id} name={con.name!r}: {repr_con}\n")
                members = api_client.member.get_members(project_id, con.id)
                print("Members:")
                for m in members:
                    repr_m = to_json_convention_string(m)
                    print(f" Type: {type(m)}    member id={m.id} name={m.name!r} cross_section_id={m.cross_section_id}: {repr_m}\n")
                print("Load effects:")
                load_effects = api_client.load_effect.get_load_effects(project_id, con.id)
                for le in load_effects:
                    repr_le = to_json_convention_string(le)
                    print(f"     Load effect id={le.id} name={le.name!r}: {repr_le}\n")
            print()
        except Exception as exc:
            print(f"   FAIL: {exc}\n")
            return

        print("4. Listing cross-sections already in the project's material list ...")
        try:
            cross_sections = api_client.material.get_cross_sections(project_id)
            for cs in cross_sections:
                # check if cross section object is instance of dict
                #print(f'cross section object is instance of dict {isinstance(cs, dict)}')
                cs_repr = json.dumps(cs, indent=2) # repr(cs)
                cs_id = cs.get("id", "?")
                cs_name = cs.get("name", "?") or cs.get("mprl_name", "?")
                print(f" Cross-section id: {cs_id}, name: {cs_name}: {cs_repr}\n")
            print()
        except Exception as exc:
            print(f"   FAIL: {exc}\n")

        print("5. Listing operations (plates/bolts/welds/cuts) and their parameters ...")
        try:
            for con in connections:
                operations = _list_operations(api_client, project_id, con.id)
                print(f"   Connection id={con.id} name={con.name!r} operations:")
                for op in operations:
                    print(f"     operation id={op.id} name={op.name!r} type={op.operation_type} active={op.active}")
                properties = _list_operations_properties(api_client, project_id, con.id)
                print(f"   Connection id={con.id} common operation properties:")
                print(f"     {properties.to_dict()}")
                parameters = _get_parameters(api_client, project_id, con.id, include_hidden=True)
                visible_parameters = [p for p in parameters if p.is_visible]
                hidden_parameters = [p for p in parameters if not p.is_visible]
                print(f"   Connection id={con.id} Hidden parameters:")
                for p in hidden_parameters:
                    print(f'Parameter: {p.to_json()}')
                print(f"   Connection id={con.id} Visible parameters:")
                for p in visible_parameters:
                    print(f'Parameter: {p.to_json()}')
                # Additionally, print only key, value, expression, and description of visible parameters
                print(f"   Connection id={con.id} Visible parameters (key, value, expression, description):")
                for p in visible_parameters:
                    p_needed_keys = {"key": p.key, "value": p.value, "expression": str(p.value), "orig_expression": p.expression, "description": p.description}
                    print(f'    {json.dumps(p_needed_keys)},')
            print()
        except Exception as exc:
            print(f"   FAIL: {exc}\n")

    print("=== self-test complete (no changes were made) ===")
    print("Use the member names/ids and parameter keys above to build design_joint()'s input JSON.")

def _main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument(
        "template_path", nargs="?",
        help="Path to a template .ideaCon project, for read-only self-test reconnaissance.",
    )
    parser.add_argument(
        "--design",
        help="Path to a design_joint() input JSON file (see design_joint_sample.json); "
             "runs design_joint() and prints the result instead of the self-test.",
    )
    args = parser.parse_args()

    if args.design:
        _run_design(args.design)
        return

    if not args.template_path:
        parser.error("template_path is required unless --design is given")
    _self_test(args.template_path)


if __name__ == "__main__":
    _main()
