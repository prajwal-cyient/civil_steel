def _to_jsonable(obj: Any) -> Any:
    """
    Best-effort conversion of an SDK model object (OpenAPI-generated
    Pydantic-style model) into plain JSON-serializable data, without
    needing to know every model's exact field list up front.
    """
    if obj is None or isinstance(obj, (str, int, float, bool)):
        return obj
    if isinstance(obj, dict):
        return {k: _to_jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_to_jsonable(v) for v in obj]
    for method_name in ("to_dict", "dict", "model_dump"):
        method = obj.get(method_name, None)
        if callable(method):
            try:
                return _to_jsonable(method())
            except Exception:
                pass
    if hasattr(obj, "__dict__"):
        return {k: _to_jsonable(v) for k, v in vars(obj).items() if not k.startswith("_")}
    return str(obj)


def _get_client(attacher_only: bool = True) -> ConnectionApiClient:
    """
    Connects to the Connection API service.

    By default attaches to an already-running service at BASE_URL (you
    started IdeaStatiCa.ConnectionRestApi.exe yourself) — cheaper for
    iterative development. Set attacher_only=False to instead let the
    SDK start the service itself from SETUP_DIR (the "runner" pattern);
    that path is async in the SDK, so it isn't wired up here — see the
    module docstring's Python boilerplate reference for that variant if
    you need it.
    """
    if ConnectionApiServiceAttacher is None:
        raise IdeaStaticaConnectionError(
            "ideastatica-connection-api is not installed "
            "(`pip install ideastatica-connection-api`, matching your IDEA StatiCa version)."
        )
    if not attacher_only:
        raise NotImplementedError(
            "Only the attacher pattern is wired up here; start "
            "IdeaStatiCa.ConnectionRestApi.exe yourself, or see the module "
            "docstring's reference to the async runner pattern."
        )
    try:
        return ConnectionApiServiceAttacher(BASE_URL).create_api_client()
    except Exception as exc:
        raise IdeaStaticaConnectionError(
            f"Could not attach to the IDEA StatiCa Connection API service at {BASE_URL}. "
            "Make sure IdeaStatiCa.ConnectionRestApi.exe is running (start it from the "
            "IDEA StatiCa install directory), and that the SDK package version matches "
            "your installed IDEA StatiCa version.\n"
            f"Underlying error: {type(exc).__name__}: {exc}"
        ) from exc


def _resolve_connection(api_client: ConnectionApiClient, project_id: StrictStr, selector: Dict[str, Any]) -> ConConnection:
    connections = api_client.connection.get_connections(project_id)
    if not connections:
        raise IdeaStaticaJointError("The template project has no connections.")

    if "id" in selector:
        for c in connections:
            if c.id == selector["id"]:
                return c
        raise IdeaStaticaJointError(f"No connection with id={selector['id']!r}.")

    if "index" in selector:
        idx = selector["index"]
        if not (0 <= idx < len(connections)):
            raise IdeaStaticaJointError(f"connection index {idx} out of range (0..{len(connections)-1}).")
        return connections[idx]

    if "name" in selector:
        needle = selector["name"].lower()
        matches = [c for c in connections if needle in (c.name or "").lower()]
        if not matches:
            names = [c.name for c in connections]
            raise IdeaStaticaJointError(
                f"No connection name contains {selector['name']!r}. Available: {names}"
            )
        return matches[0]

    raise IdeaStaticaJointError("connection_selector must have 'id', 'index', or 'name'.")


def _resolve_member(members: List[ConMember], member_name: str):
    needle = member_name.lower()
    matches = [m for m in members if needle in (m.name or "").lower()]
    if not matches:
        names = [m.name for m in members]
        raise IdeaStaticaJointError(
            f"No member name contains {member_name!r}. Available: {names}"
        )
    return matches[0]


def _free_end_position(member: ConMember) -> str:
    # Load can only be applied at the free end (not the end attached to
    # the joint), or the API rejects it with a "Position:X is not
    # defined in connection" 422 error.
    connected_by = member.connected_by
    #TODO: Should the free end be opposite to the connected_by end?
    if connected_by == ConMemberConnectedByEnum.BEGIN:
        return ConLoadEffectPositionEnum.END
    if connected_by == ConMemberConnectedByEnum.END:
        return ConLoadEffectPositionEnum.BEGIN
    raise IdeaStaticaJointError(
        f"Member {member.name!r} has no connected_by set; can't determine its free end."
    )


def _resolve_cross_section_id(api_client: ConnectionApiClient, project_id: StrictStr, mprl_cross_section_name: str, mprl_material_name: str) -> int:
    """
    Ensures a cross-section (name + material) exists in the project's
    material list, adding it from the MPRL library if not already
    present, and returns its id for use as ConMember.cross_section_id.

    UNVERIFIED: the docs describe add_cross_section as "adds an MPRL
    cross-section" without stating the exact return type name. This
    tries the most likely case (the call returns the created object
    directly, with an `.id`) and falls back to re-reading
    get_cross_sections() and matching by name if that doesn't pan out —
    if BOTH fail, this will raise clearly rather than silently doing the
    wrong thing.
    """
    existing = api_client.material.get_cross_sections(project_id)
    for cs in existing:
        cs_name = cs.get("name") or cs.get("mprl_name")
        if cs_name and cs_name.lower() == mprl_cross_section_name.lower():
            print(f"Found existing cross-section '{mprl_cross_section_name}' with id {cs['id']}")
            return cs["id"]

    print(f"Adding cross-section '{mprl_cross_section_name}' with material '{mprl_material_name}'")
    added = api_client.material.add_cross_section(
        project_id,
        ConMprlCrossSection(material_name=mprl_material_name, mprl_name=mprl_cross_section_name),
    )
    added_id = added.get("id", None) or added.get("cross_section_id", None)
    if added_id is not None:
        print(f"Added cross-section '{mprl_cross_section_name}' with id {added_id}")
        return added_id

    # Fallback: re-fetch and match by name.
    refreshed = api_client.material.get_cross_sections(project_id)
    for cs in refreshed:
        cs_name = cs.get("name") or cs.get("mprl_name")
        if cs_name and cs_name.lower() == mprl_cross_section_name.lower():
            print(f"Found cross-section '{mprl_cross_section_name}' with id {cs['id']} after refresh")
            return cs["id"]

    raise IdeaStaticaJointError(
        f"Added cross-section '{mprl_cross_section_name}' but could not determine its id "
        "from the API response — inspect add_cross_section()'s actual return value."
    )


