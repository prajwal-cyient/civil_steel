"""
idea_statica_integration.py

Sends a joint's member/load data into IDEA StatiCa Connection via the
official Connection API (REST, Python SDK: ideastatica-connection-api),
runs the CBFEM calculation, and pulls back the check results plus the
actual designed geometry (plates/bolts/welds) via IOM export.

WHAT IDEA STATICA NEEDS (read this first)
---------------------------------------------
The public Connection API CANNOT create plates, bolts, welds, or cuts
from scratch — there is no add_plate/add_bolt/add_weld/add_cut endpoint.
Connection geometry can only be authored by:
  1. Opening an existing .ideaCon file whose connection already has a
     template applied (built once, by hand, in the IDEA StatiCa desktop
     app) — the path this module uses.
  2. The Connection Library "propose" pipeline, which can pick a
     matching template automatically from a bare connection's topology
     (see connection_library.propose() in the SDK) — not used here, but
     a reasonable next step if you don't want to hand-build a template.
  3. Importing an IOM (IDEA Open Model) XML file — a from-scratch model
     format, documented primarily for C#/.NET; meaningfully more work in
     Python and not attempted here.

So: before this module can do anything useful, you need ONE .ideaCon
project file per joint TYPE (e.g. "column-beam-longitudinal-brace"),
built once in the desktop app with the connection's members, template,
and manufacturing operations (plates/bolts/welds) already in place. This
module then automates the repeatable part: swapping in this specific
joint's member cross-sections and applied loads, recalculating, and
extracting results — for every joint instance of that type generated by
generate_grid.py.

WHAT COMES BACK OUT
-----------------------
- Summary: pass/fail per connection, plus one utilization percentage per
  named check (plates, bolts, welds, ...).
- Raw JSON: the full CBFEM solver output (deepest level the public API
  exposes) via get_raw_json_results().
- IOM connection data: the actual geometric/manufacturing design (plate
  dimensions, bolt positions/grades, weld sizes) via
  export_iom_connection_data() — this is the real "what got designed"
  answer, as distinct from the check results above.
- PDF report, if you want a human-readable one too.

CONFIDENCE LEVEL
-------------------
Unlike the early STAAD integration work, this module is built directly
from IDEA StatiCa's own official, dated documentation (verified against
SDK 26.0.2.0407 / API 3.0, June 2026) rather than general knowledge, so
method names and signatures should be accurate. What's NOT verified:
  - The exact return shape of material.add_cross_section() (used to
    resolve a cross_section_id for member updates) — the docs describe
    its behavior but not its return type name. This module tries the
    most likely shape defensively; see _resolve_cross_section_id().
  - How your specific template project names its members — there's no
    way to know this without opening the actual file, which is why the
    self-test below just lists connections/members for you to inspect
    first, rather than assuming names.
  - Real load effect values: no load-calculation logic exists yet
    upstream (see staad_integration.py's LOAD CONFIGURATION SCHEMA notes
    on the same open question) — the self-test uses placeholder forces.

REQUIREMENTS
--------------
  - IDEA StatiCa 24.1+ installed, with a valid non-Basic license.
  - The Connection API service running: either start
    "IdeaStatiCa.ConnectionRestApi.exe" yourself from the IDEA StatiCa
    install directory (default port 5000), or let this module start it
    via the "runner" pattern (IDEA_STATICA_SETUP_DIR below).
  - `pip install ideastatica-connection-api`, version matching your
    installed IDEA StatiCa version exactly (e.g. 26.0.x for IDEA StatiCa
    26.0) — mismatched versions cause 404s/deserialization errors.

INPUT SHAPE for design_joint()
----------------------------------
{
  "template_project_path": "C:\\joints\\column_beam_brace.ideaCon",
  "connection_selector": {"name": "column-beam-brace"},   // or {"id": 1} or {"index": 0}
  "member_updates": [
    {"member_name": "Column", "cross_section_mprl_name": "CFRHS120X120X5", "material_mprl_name": "S 355"}
  ],
  "load_effect": {
    "name": "LC1 - generated",
    "member_loadings": [
      {"member_name": "Column", "n": -120.0, "vy": 5.0, "vz": 0.0, "mx": 0.0, "my": 12.0, "mz": 0.0}
    ]
  },
  "output_dir": "C:\\joints\\output\\column_beam_brace_0_0",
  "save_project_path": "C:\\joints\\output\\column_beam_brace_0_0\\column_beam_brace_0_0.ideaCon"
}

member_name / cross_section_mprl_name / material_mprl_name are matched
case-insensitively as substrings against the template's actual member
names and the MPRL catalog names respectively — MPRL names are IDEA
StatiCa's OWN catalog naming, a third convention distinct from both the
Tekla profile strings and the STAAD table names used elsewhere in this
project (e.g. likely "CFRHS120X120X5" rather than Tekla's
"CFRHS120X120X5" verbatim, or "HE 140 A" rather than "HEA140" — check
the MPRL library in the desktop app if a cross-section add fails).

Note: there is no "position" field on a member_loading — the load is
always applied at the member's free end (the end not attached to the
joint), which this module derives automatically from
ConMember.connected_by. Supplying a position yourself isn't possible
because the API rejects loads placed at the joint-attached end.

Sample cmd to run this utility:
To view the parameters of a connection without performing a design, use:
python idea_statica_integration.py sample_projects/Transverese_bracing_conn_detail.ideaCon

To perform a design using the JSON input, use: (NOTE: The json file contains idea statica connection file)
python idea_statica_integration.py --design Transverese_bracing_conn_detail.json.json
"""

