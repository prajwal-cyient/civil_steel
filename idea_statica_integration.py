def design_joint(data: dict) -> dict:
    """
    Opens a template .ideaCon project, selects one connection (joint),
    updates the given members' cross-sections and the joint's load
    effect, recalculates, and returns check results plus file paths for
    the raw JSON results, IOM connection data export, and PDF report.

    See the module docstring for the exact input shape and for why a
    template project (built once by hand) is required.

    The template's .ideaCon file on disk is NOT modified in place — the
    service works on its own in-memory/temp copy of the project keyed by
    project_id. To persist the member/load changes made here as an
    .ideaCon file, pass "save_project_path" in `data`; this calls
    project.download_project() before the project is closed. Without it,
    the changes only exist for the lifetime of this call (results/exports
    are still written to output_dir regardless).

    OPERATION PARAMETERS (plates/bolts/welds)
    ------------------------------------------
    The manufacturing operations themselves (which plates/bolts/welds
    exist) come from the template and can't be created here — see the
    module docstring. Their design values (plate thickness, bolt type,
    weld size, etc. — what you'd edit in the operation's property panel
    in the desktop app) CAN be changed, but only for fields the template
    author has explicitly exposed as a Parameter via Developer Mode in
    the desktop app first (IDEA StatiCa's Parameters feature does not
    auto-expose every GUI field — see
    https://developer.ideastatica.com/docs/api/api_parameters_getting_started.html).
    Once exposed, use the optional "operation_parameters" input:
        "operation_parameters": [{"key": "CPL3_Thickness", "expression": "12"}]
    Parameter `key` names are whatever the template author chose when
    linking the field in Developer Mode — list them first with this
    module's self-test (step 5) to find the actual keys for your
    template. The resolved parameters (after any updates) are returned
    under "operation_parameters" in the result.

    Returns
    -------
    dict
        {
          "connection_id": <int>,
          "passed": <bool>,
          "check_summary": [{"name":..., "check_value":..., "check_status":..., "skipped":...}, ...],
          "raw_results_file": <str>,
          "iom_connection_data_file": <str>,
          "report_pdf_file": <str>,
          "saved_project_path": <str or None>,
          "operation_parameters": [{"key":..., "value":..., "unit":..., "description":...}, ...],
        }
    """
    template_path = data["template_project_path"]
    connection_selector = data["connection_selector"]
    member_updates = data.get("member_updates", [])
    load_effect_specs = data.get("load_effects")
    operation_parameter_updates = data.get("operation_parameters", [])
    output_dir = data["output_dir"]
    save_project_path = data.get("save_project_path")
    os.makedirs(output_dir, exist_ok=True)

    with _get_client() as api_client:
        api_client.project.open_project_from_filepath(template_path)
        project_id = api_client.project.active_project_id
        settings = api_client.settings.get_settings(project_id)
        #print(f"   Retrieved project settings: {to_json_convention_string(settings)}\n")

        connection = _resolve_connection(api_client, project_id, connection_selector)
        connection_id = connection.id

        members = api_client.member.get_members(project_id, connection_id)

        print(f"Updating {project_id} with connection {connection_id}")
        # ---- Member cross-section/material updates ----
        for update in member_updates:
            try:
                member = _resolve_member(members, update["member_name"])
            except Exception as e:
                print(f"Warning: Not able to resolve member {update['member_name']}. Ignoring update.: {e}")
                continue
            cross_section_id = _resolve_cross_section_id(
                api_client, project_id,
                update["cross_section_mprl_name"], update["material_mprl_name"],
            )
            member.cross_section_id = cross_section_id
            if "gama_pitch" in update:
                member.position.gama_pitch = float(update["gama_pitch"])*pi/180 # convert degrees to radians
            #TODO: This does not work as ConMember does not have aligned_plate or related_plate attributes by default, they are being added dynamically here.
            # Modified patch/con_member.py to include these fields but that does work either.
            if "aligned_plate" in update:
                aligned_plate = update["aligned_plate"]
                aligned_plate_member_id = _resolve_member(members, aligned_plate["member"])
                member.model_config["validate_assignment"] = False
                member.aligned_plate = ConAlignedPlate(
                    plate_side=aligned_plate["plate_side"],
                    member_id=aligned_plate_member_id.id,
                    part_type=aligned_plate["part_type"]
                )
                member.model_config["validate_assignment"] = True
            if "related_plate" in update:
                related_plate = update["related_plate"]
                related_plate_member_id = _resolve_member(members, related_plate["member"])
                member.model_config["validate_assignment"] = False
                member.related_plate = ConAlignedPlate(
                    plate_side=related_plate["plate_side"],
                    member_id=related_plate_member_id.id,
                    part_type=related_plate["part_type"]
                )
                member.model_config["validate_assignment"] = True
            api_client.member.update_member(project_id, connection_id, member)
        print(f"Updated members for connection {connection_id}")
        # ---- Load effect ----
        for load_effect_spec in load_effect_specs:
            print(f"Applying load effect for connection {connection_id}: {load_effect_spec.get('name', '')}")
            member_loadings: List[ConLoadEffectMemberLoad] = []
            for loading in load_effect_spec.get("member_loadings", []):
                member = _resolve_member(members, loading["member_name"])
                # The joint's fixed end can't take a load; position is
                # derived from the member's actual free end, not guessed.
                specified_position = loading.get("position", "")
                if specified_position and specified_position.lower() in ["start", "begin"]:
                    position = ConLoadEffectPositionEnum.BEGIN
                elif specified_position and specified_position.lower() in ["end"]:
                    position = ConLoadEffectPositionEnum.END
                else:
                    position = _free_end_position(member)
                # Convert loads from kN and kNm to N and Nmm for the API
                member_loadings.append(ConLoadEffectMemberLoad(
                    member_id=member.id,
                    position=position,
                    section_load=ConLoadEffectSectionLoad(
                        n=loading.get("n", 0)*1000.0, vy=loading.get("vy", 0)*1000.0, vz=loading.get("vz", 0)*1000.0,
                        mx=loading.get("mx", 0)*1000.0, my=loading.get("my", 0)*1000.0, mz=loading.get("mz", 0)*1000.0,
                    ),
                ))
            api_client.load_effect.add_load_effect(
                project_id, connection_id,
                ConLoadEffect(
                    name=load_effect_spec.get("name", "Generated load"),
                    active=True,
                    member_loadings=member_loadings,
                ),
            )
            print(f"Applied load effect for connection {connection_id}: {load_effect_spec.get('name', '')}")

        # ---- Operation parameters (plate/bolt/weld dimensions) ----
        if operation_parameter_updates:
            print(f"Setting operation parameters for connection {connection_id}")
            _set_parameters(api_client, project_id, connection_id, operation_parameter_updates)
            print(f"Set operation parameters for connection {connection_id}")
        operation_parameters = [
            {
                "key": p.key,
                "value": p.value,
                "unit": p.unit,
                "expression": p.expression,
                "description": p.description,
            }
            for p in _get_parameters(api_client, project_id, connection_id)
        ]

        # ---- Persist the modified project (member/load changes) to disk ----
        # Must happen before the client's __exit__ calls close_project().
        if save_project_path:
            print(f"Saving project to {save_project_path}")
            os.makedirs(os.path.dirname(save_project_path) or ".", exist_ok=True)
            api_client.project.download_project(project_id, save_project_path)
            print(f"Saved project to {save_project_path}")

        print(f"Calculating results for connection {connection_id}")
        start = time.time()
        # ---- Calculate ----
        results = api_client.calculation.calculate(project_id, [connection_id])
        result = results[0]
        print(f"Calculation completed for connection {connection_id} in {time.time() - start:.2f} seconds. Number of results: {len(results)}")
        print(f"Extracting check summary for connection {connection_id}")
        check_summary = [
            {
                "name": c.name,
                "check_value": c.check_value,
                "check_status": c.check_status,
                "skipped": c.skipped,
            }
            for c in (result.result_summary or [])
        ]
        check_summary = {"summary": check_summary, "operation_parameters": operation_parameters}
        summary_file = os.path.join(output_dir, "check_summary.json")
        with open(summary_file, "w") as f:
            json.dump(check_summary, f, indent=2)
        print(f"Extracted check summary for connection {connection_id}")

        print(f"Extracting IOM connection data for connection {connection_id}")
        iom_connection_data_file = os.path.join(output_dir, "iom_connection_data.json")
        start = time.time()
        connection_data = api_client.export.export_iom_connection_data(project_id, connection_id)
        print(f"Extracted IOM connection data for connection {connection_id} in {time.time() - start:.2f} seconds")
        start = time.time()
        with open(iom_connection_data_file, "w") as f:
            f.write(json.dumps(connection_data.to_dict(), indent=2))
        print(f"Extracted and saved IOM connection data for connection {connection_id} in {time.time() - start:.2f} seconds")

        extract_raw_results = data.get("extract_raw_results", False)
        if extract_raw_results:
            # ---- Extract results ----
            print(f"Extracting raw results for connection {connection_id}")
            start = time.time()
            raw_results_file = os.path.join(output_dir, "raw_cbfem_results.json")
            raw_json_list = api_client.calculation.get_raw_json_results(project_id, [connection_id])
            with open(raw_results_file, "w") as f:
                f.write(raw_json_list[0])
            print(f"Extracted raw results for connection {connection_id} in {time.time() - start:.2f} seconds. Number of raw results: {len(raw_json_list)}")

        extract_pdf_report = data.get("extract_pdf_report", False)
        if extract_pdf_report:
            print(f"Generating report PDF for connection {connection_id}")
            report_pdf_file = os.path.join(output_dir, "report.pdf")
            start = time.time()
            api_client.report.save_report_pdf(project_id, connection_id, report_pdf_file)
            print(f"Generated report PDF for connection {connection_id} in {time.time() - start:.2f} seconds")
    return {
        "connection_id": connection_id,
        "passed": result.passed,
        "check_summary": check_summary,
        "check_summary_file": summary_file,
        "raw_results_file": raw_results_file if extract_raw_results else None,
        "iom_connection_data_file": iom_connection_data_file,
        "report_pdf_file": report_pdf_file if extract_pdf_report else None,
        "saved_project_path": save_project_path,
    }

def to_json_convention_string(obj: Any) -> str:
    return str(obj).replace('\'', '\"').replace('None', 'null').replace('True', 'true').replace('False', 'false')

