#
# Run this file directly to either:
#   - `python idea_statica_integration.py <path-to-ideaCon>` : read-only
#     reconnaissance (lists connections/members/load effects/cross-sections)
#     on the machine with IDEA StatiCa + the matching SDK installed, with
#     IdeaStatiCa.ConnectionRestApi.exe already running.
